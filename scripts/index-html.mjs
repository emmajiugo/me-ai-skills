const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

export function renderIndex(skills) {
  const auto = skills.filter((s) => s.auto).length;
  const cards = skills.map(card).join("\n");

  return `<!doctype html>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>me-ai-skills</title>
<style>
  :root {
    --bg: #fbfaf8; --panel: #fff; --ink: #1c1b19; --muted: #6b6862;
    --line: #e4e0d8; --accent: #7a4a1e; --auto: #2f5d3a; --manual: #6b6862;
  }
  @media (prefers-color-scheme: dark) {
    :root {
      --bg: #161513; --panel: #1e1d1a; --ink: #ece9e3; --muted: #97928a;
      --line: #302e2a; --accent: #d8a15f; --auto: #7bb98c; --manual: #97928a;
    }
  }
  * { box-sizing: border-box }
  body {
    margin: 0; background: var(--bg); color: var(--ink);
    font: 15px/1.55 ui-sans-serif, -apple-system, "Segoe UI", system-ui, sans-serif;
    padding: 3rem 1.5rem 5rem;
  }
  main { max-width: 62rem; margin: 0 auto }
  h1 { font-size: 1.6rem; margin: 0 0 .3rem; letter-spacing: -.01em }
  .sub { color: var(--muted); margin: 0 0 1.6rem }
  input {
    width: 100%; padding: .7rem .9rem; font: inherit; color: inherit;
    background: var(--panel); border: 1px solid var(--line); border-radius: 8px;
  }
  input:focus { outline: 2px solid var(--accent); outline-offset: 1px }
  .count { color: var(--muted); font-size: .82rem; margin: .8rem 0 1.4rem }
  .grid { display: grid; gap: .75rem }
  article {
    background: var(--panel); border: 1px solid var(--line); border-radius: 10px;
    padding: 1rem 1.1rem;
  }
  .top { display: flex; align-items: baseline; gap: .6rem; flex-wrap: wrap }
  h2 { font-size: .98rem; margin: 0; font-family: ui-monospace, SFMono-Regular, Menlo, monospace }
  .tag {
    font-size: .68rem; letter-spacing: .04em; text-transform: uppercase;
    border: 1px solid var(--line); border-radius: 999px; padding: .1rem .5rem;
  }
  .tag.auto { color: var(--auto); border-color: currentColor }
  .tag.manual { color: var(--manual) }
  .src { margin-left: auto; font-size: .75rem }
  .src a { color: var(--muted); text-decoration: none }
  .src a:hover { color: var(--accent); text-decoration: underline }
  p.desc { margin: .55rem 0 0; color: var(--ink) }
  .empty { color: var(--muted); padding: 2rem 0 }
  footer { margin-top: 2.5rem; color: var(--muted); font-size: .8rem }
  code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: .85em }
</style>
<main>
  <h1>me-ai-skills</h1>
  <p class="sub">Shared by Claude Code and opencode from one directory.</p>
  <input id="q" type="search" placeholder="Filter by name or description" autofocus>
  <p class="count"><span id="n">${skills.length}</span> of ${skills.length} skills &middot; ${auto} run on their own, ${skills.length - auto} you invoke by name</p>
  <div class="grid" id="grid">
${cards}
  </div>
  <p class="empty" id="none" hidden>Nothing matches.</p>
  <footer>Generated by <code>make build</code>. Do not edit this file.</footer>
</main>
<script>
  const q = document.getElementById("q"), n = document.getElementById("n");
  const cards = [...document.querySelectorAll("article")];
  const none = document.getElementById("none");
  q.addEventListener("input", () => {
    const t = q.value.trim().toLowerCase();
    let shown = 0;
    for (const c of cards) {
      const hit = !t || c.dataset.search.includes(t);
      c.hidden = !hit;
      if (hit) shown++;
    }
    n.textContent = shown;
    none.hidden = shown > 0;
  });
</script>
`;
}

function card(s) {
  const search = esc(`${s.name} ${s.description} ${s.sourceLabel}`.toLowerCase());
  const badge = s.auto
    ? '<span class="tag auto">auto</span>'
    : '<span class="tag manual">on request</span>';
  const src = s.source
    ? `<span class="src"><a href="${esc(s.source)}">${esc(s.sourceLabel)}</a></span>`
    : '<span class="src">local</span>';
  return `    <article data-search="${search}">
      <div class="top"><h2>${esc(s.name)}</h2>${badge}${src}</div>
      <p class="desc">${esc(s.description)}</p>
    </article>`;
}
